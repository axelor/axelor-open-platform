package com.axelor.script;

import groovy.lang.Closure;
import groovyjarjarasm.asm.ClassReader;
import groovyjarjarasm.asm.ClassVisitor;
import groovyjarjarasm.asm.ClassWriter;
import groovyjarjarasm.asm.MethodVisitor;
import groovyjarjarasm.asm.Opcodes;
import groovyjarjarasm.asm.Type;
import org.codehaus.groovy.control.BytecodeProcessor;

/**
 * Makes the closures compiled by {@link GroovyScriptSupport} extend {@link SandboxClosure} instead
 * of {@link Closure}.
 *
 * <p>The Groovy compiler always generates closure classes extending {@link Closure}, so their
 * superclass is replaced in the generated bytecode: the class header and the super constructor
 * calls. {@link SandboxClosure} has the same constructors, so nothing else changes.
 */
class SandboxClosureProcessor implements BytecodeProcessor {

  private static final String CLOSURE = Type.getInternalName(Closure.class);
  private static final String SANDBOX_CLOSURE = Type.getInternalName(SandboxClosure.class);

  @Override
  public byte[] processBytecode(String name, byte[] original) {
    ClassReader reader = new ClassReader(original);
    if (!CLOSURE.equals(reader.getSuperName())) {
      return original;
    }
    ClassWriter writer = new ClassWriter(reader, 0);
    reader.accept(new SuperclassVisitor(writer), 0);
    return writer.toByteArray();
  }

  private static class SuperclassVisitor extends ClassVisitor {

    SuperclassVisitor(ClassVisitor next) {
      super(Opcodes.ASM9, next);
    }

    @Override
    public void visit(
        int version,
        int access,
        String name,
        String signature,
        String superName,
        String[] interfaces) {
      super.visit(version, access, name, signature, SANDBOX_CLOSURE, interfaces);
    }

    @Override
    public MethodVisitor visitMethod(
        int access, String name, String descriptor, String signature, String[] exceptions) {
      MethodVisitor mv = super.visitMethod(access, name, descriptor, signature, exceptions);
      if (!"<init>".equals(name)) {
        return mv;
      }
      return new MethodVisitor(Opcodes.ASM9, mv) {
        @Override
        public void visitMethodInsn(
            int opcode, String owner, String name, String descriptor, boolean isInterface) {
          // super(...) constructor call
          if (opcode == Opcodes.INVOKESPECIAL && CLOSURE.equals(owner) && "<init>".equals(name)) {
            owner = SANDBOX_CLOSURE;
          }
          super.visitMethodInsn(opcode, owner, name, descriptor, isInterface);
        }
      };
    }
  }
}
