package com.axelor.script;

import java.util.function.Consumer;
import org.codehaus.groovy.ast.ASTNode;
import org.codehaus.groovy.ast.ClassCodeExpressionTransformer;
import org.codehaus.groovy.ast.ClassHelper;
import org.codehaus.groovy.ast.ClassNode;
import org.codehaus.groovy.ast.expr.ArgumentListExpression;
import org.codehaus.groovy.ast.expr.ClosureExpression;
import org.codehaus.groovy.ast.expr.ConstructorCallExpression;
import org.codehaus.groovy.ast.expr.Expression;
import org.codehaus.groovy.ast.expr.MethodCallExpression;
import org.codehaus.groovy.ast.expr.PropertyExpression;
import org.codehaus.groovy.ast.expr.StaticMethodCallExpression;
import org.codehaus.groovy.ast.expr.VariableExpression;
import org.codehaus.groovy.ast.stmt.BlockStatement;
import org.codehaus.groovy.ast.stmt.DoWhileStatement;
import org.codehaus.groovy.ast.stmt.ExpressionStatement;
import org.codehaus.groovy.ast.stmt.ForStatement;
import org.codehaus.groovy.ast.stmt.LoopingStatement;
import org.codehaus.groovy.ast.stmt.Statement;
import org.codehaus.groovy.ast.stmt.WhileStatement;
import org.codehaus.groovy.control.CompilePhase;
import org.codehaus.groovy.control.SourceUnit;
import org.codehaus.groovy.transform.AbstractASTTransformation;
import org.codehaus.groovy.transform.GroovyASTTransformation;

/**
 * A custom groovy ast transformer to validate type of objects against the policy settings.
 *
 * <p>This transformer will transform the ctor/method/property calls by wrapping the object side in
 * a {@link GroovySandbox} check.
 *
 * <p>It will also transform loop and if blocks and adds timeout check.
 *
 * <p>For example:
 *
 * <pre>
 * def value = some.method()
 *
 * while(true) {
 *   println('Hello')
 * }
 * </pre>
 *
 * would become:
 *
 * <pre>
 * def value = GroovySandbox.check(some).method()
 *
 * while(true) {
 *   GroovySandbox.timeout()
 *   GroovySandbox.check(this).println('Hello')
 * }
 * </pre>
 */
@GroovyASTTransformation(phase = CompilePhase.CONVERSION)
public class GroovyCheckTransformation extends AbstractASTTransformation {

  @Override
  public void visit(ASTNode[] nodes, SourceUnit source) {

    CheckTransformer checkTransformer = new CheckTransformer(source);
    LoopTransformer loopTransformer = new LoopTransformer(source);

    for (ASTNode node : nodes) {
      if (node instanceof ClassNode classNode) {
        checkTransformer.visitClass(classNode);
        loopTransformer.visitClass(classNode);
      }
    }
  }

  private static final ClassNode SANDBOX = ClassHelper.make(GroovySandbox.class);

  /**
   * A call to a static {@link GroovySandbox} method. It is resolved at compile time against the
   * class, so a script cannot shadow it (unlike a variable, which a local variable or a closure
   * delegate could replace).
   */
  static Expression sandboxCallX(String method, ArgumentListExpression args) {
    return new StaticMethodCallExpression(SANDBOX, method, args);
  }

  /** Whether the expression is a check generated by {@link #receiverCheckX}. */
  static boolean isSandboxCall(Expression expr) {
    return expr instanceof StaticMethodCallExpression call && call.getOwnerType().equals(SANDBOX);
  }

  /**
   * Checks the receiver of a call or property access. For a spread ({@code recv*.name}), the call
   * is dispatched on each element of the receiver, so the elements are checked instead.
   */
  static Expression receiverCheckX(Expression receiver, boolean spread) {
    return sandboxCallX(
        spread ? GroovySandbox.CALL_CHECK_SPREAD : GroovySandbox.CALL_CHECK,
        new ArgumentListExpression(receiver));
  }

  static class CheckTransformer extends ClassCodeExpressionTransformer {

    private final SourceUnit unit;

    public CheckTransformer(SourceUnit unit) {
      this.unit = unit;
    }

    @Override
    protected SourceUnit getSourceUnit() {
      return unit;
    }

    @Override
    public Expression transform(Expression expr) {

      if (expr instanceof PropertyExpression) {
        PropertyExpression prop = (PropertyExpression) super.transform(expr);
        Expression obj = prop.getObjectExpression();
        if (obj instanceof MethodCallExpression) {
          PropertyExpression res =
              new PropertyExpression(
                  receiverCheckX(obj, prop.isSpreadSafe()), prop.getProperty(), prop.isSafe());
          res.setSpreadSafe(prop.isSpreadSafe());
          return res;
        }
        return prop;
      }

      if (expr instanceof ConstructorCallExpression call) {
        // super(...) / this(...): must stay the first statement of a constructor, and only call a
        // constructor of the class itself or of its superclass (allowed, see GroovyClassCheck)
        if (call.isSpecialCall()) {
          return super.transform(expr);
        }
        return receiverCheckX(super.transform(expr), false);
      }

      if (expr instanceof MethodCallExpression) {
        MethodCallExpression method = (MethodCallExpression) super.transform(expr);

        // super.method(...): calls the superclass method (allowed, see GroovyClassCheck); wrapping
        // the receiver would call the overriding method instead
        if (method.getObjectExpression() instanceof VariableExpression variable
            && variable.isSuperExpression()) {
          return method;
        }

        MethodCallExpression res =
            new MethodCallExpression(
                receiverCheckX(method.getObjectExpression(), method.isSpreadSafe()),
                method.getMethod(),
                method.getArguments());
        res.setSafe(method.isSafe());
        res.setSpreadSafe(method.isSpreadSafe());
        return res;
      }

      if (expr instanceof ClosureExpression ce) {
        if (ce.getCode() != null) {
          ce.getCode().visit(this);
        }
        return ce;
      }

      return super.transform(expr);
    }
  }

  static class LoopTransformer extends ClassCodeExpressionTransformer {

    private final SourceUnit unit;

    public LoopTransformer(SourceUnit unit) {
      this.unit = unit;
    }

    @Override
    protected SourceUnit getSourceUnit() {
      return unit;
    }

    @Override
    public void visitForLoop(ForStatement stmt) {
      super.visitForLoop(stmt);
      transformLoop(stmt);
    }

    @Override
    public void visitWhileLoop(WhileStatement stmt) {
      super.visitWhileLoop(stmt);
      transformLoop(stmt);
    }

    @Override
    public void visitDoWhileLoop(DoWhileStatement stmt) {
      super.visitDoWhileLoop(stmt);
      transformLoop(stmt);
    }

    private <T extends LoopingStatement> void transformLoop(T stmt) {
      addTimeout(stmt.getLoopBlock(), stmt::setLoopBlock);
    }

    private void addTimeout(Statement block, Consumer<BlockStatement> accept) {
      BlockStatement wrapped = toBlockStatement(block);
      wrapped.getStatements().add(0, checkX());
      accept.accept(wrapped);
    }

    private BlockStatement toBlockStatement(Statement stmt) {
      if (stmt instanceof BlockStatement blockStmt) {
        return blockStmt;
      }
      BlockStatement block = new BlockStatement();
      block.addStatement(stmt);
      return block;
    }

    private Statement checkX() {
      return new ExpressionStatement(
          sandboxCallX(GroovySandbox.CALL_TIMEOUT, ArgumentListExpression.EMPTY_ARGUMENTS));
    }
  }
}
