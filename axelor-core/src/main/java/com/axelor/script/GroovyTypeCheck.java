package com.axelor.script;

import groovy.lang.Closure;
import org.codehaus.groovy.ast.ClassCodeVisitorSupport;
import org.codehaus.groovy.ast.ClassNode;
import org.codehaus.groovy.ast.FieldNode;
import org.codehaus.groovy.ast.MethodNode;
import org.codehaus.groovy.ast.Parameter;
import org.codehaus.groovy.ast.PropertyNode;
import org.codehaus.groovy.ast.expr.ArrayExpression;
import org.codehaus.groovy.ast.expr.CastExpression;
import org.codehaus.groovy.ast.expr.ClosureExpression;
import org.codehaus.groovy.ast.expr.DeclarationExpression;
import org.codehaus.groovy.ast.expr.Expression;
import org.codehaus.groovy.ast.expr.TupleExpression;
import org.codehaus.groovy.ast.expr.VariableExpression;
import org.codehaus.groovy.ast.stmt.ForStatement;
import org.codehaus.groovy.classgen.GeneratorContext;
import org.codehaus.groovy.control.CompilePhase;
import org.codehaus.groovy.control.SourceUnit;
import org.codehaus.groovy.control.customizers.CompilationCustomizer;

/**
 * Validates the types written in scripts: of variables, fields, properties, parameters, return
 * values, casts and array initializers.
 *
 * <p>Groovy converts a value to such a type implicitly, and converts a list or map by calling a
 * constructor of the type: {@code java.io.FileOutputStream f = ['/path']} creates a file, with no
 * call the receiver checks could see. The elements of an array initializer ({@code new
 * java.io.FileOutputStream[] { ['/path'] }}) are converted to the element type the same way. A map
 * or a closure converted to an abstract class constructs a proxy subclass of it, running its
 * constructor. So concrete and abstract classes written as types must be allowed by the policy,
 * except {@link Closure} ({@code Closure c = { ... }}). Interfaces and catch parameters are not
 * converted this way, so they are not checked. Members generated by the compiler, without source
 * position, are not checked either.
 *
 * <p>This runs once types are resolved, in the {@link CompilePhase#CANONICALIZATION} phase.
 */
class GroovyTypeCheck extends CompilationCustomizer {

  GroovyTypeCheck() {
    super(CompilePhase.CANONICALIZATION);
  }

  @Override
  public void call(SourceUnit source, GeneratorContext context, ClassNode classNode) {
    new TypeVisitor(source).visitClass(classNode);
  }

  private static void check(ClassNode type, int line) {
    // without source position: generated by the compiler (e.g. the Binding constructor of scripts)
    if (line < 0) {
      return;
    }
    Class<?> klass = GroovyTypes.resolve(type);
    if (klass != null
        && klass != Closure.class
        && GroovySandbox.isConstructible(klass)
        && !ScriptPolicy.getInstance().allowed(klass)) {
      throw new ScriptPolicyException(
          String.format("Type '%s' not allowed (line %d).", klass.getName(), line));
    }
  }

  private static void check(Parameter[] parameters) {
    if (parameters != null) {
      for (Parameter parameter : parameters) {
        check(parameter.getOriginType(), parameter.getLineNumber());
      }
    }
  }

  private static class TypeVisitor extends ClassCodeVisitorSupport {

    private final SourceUnit source;

    TypeVisitor(SourceUnit source) {
      this.source = source;
    }

    @Override
    protected SourceUnit getSourceUnit() {
      return source;
    }

    @Override
    public void visitField(FieldNode node) {
      check(node.getOriginType(), node.getLineNumber());
      super.visitField(node);
    }

    @Override
    public void visitProperty(PropertyNode node) {
      check(node.getOriginType(), node.getLineNumber());
      super.visitProperty(node);
    }

    @Override
    protected void visitConstructorOrMethod(MethodNode node, boolean isConstructor) {
      if (!isConstructor) {
        check(node.getReturnType(), node.getLineNumber());
      }
      check(node.getParameters());
      visitInitialExpressions(node.getParameters());
      super.visitConstructorOrMethod(node, isConstructor);
    }

    @Override
    public void visitDeclarationExpression(DeclarationExpression expression) {
      Expression left = expression.getLeftExpression();
      if (left instanceof VariableExpression variable) {
        check(variable.getOriginType(), expression.getLineNumber());
      } else if (left instanceof TupleExpression tuple) {
        for (Expression element : tuple.getExpressions()) {
          if (element instanceof VariableExpression variable) {
            check(variable.getOriginType(), expression.getLineNumber());
          }
        }
      }
      super.visitDeclarationExpression(expression);
    }

    @Override
    public void visitCastExpression(CastExpression expression) {
      check(expression.getType(), expression.getLineNumber());
      super.visitCastExpression(expression);
    }

    // An array without initializer (new X[size]) only holds nulls: nothing is converted.
    @Override
    public void visitArrayExpression(ArrayExpression expression) {
      if (expression.getExpressions() != null && !expression.getExpressions().isEmpty()) {
        check(expression.getElementType(), expression.getLineNumber());
      }
      super.visitArrayExpression(expression);
    }

    @Override
    public void visitClosureExpression(ClosureExpression expression) {
      check(expression.getParameters());
      visitInitialExpressions(expression.getParameters());
      super.visitClosureExpression(expression);
    }

    // The default values of parameters (def f(x = expr), { x = expr -> }) are code too, but
    // ClassCodeVisitorSupport only visits the code of methods and closures, not their parameters.
    private void visitInitialExpressions(Parameter[] parameters) {
      if (parameters != null) {
        for (Parameter parameter : parameters) {
          if (parameter.hasInitialExpression()) {
            parameter.getInitialExpression().visit(this);
          }
        }
      }
    }

    @Override
    public void visitForLoop(ForStatement statement) {
      Parameter variable = statement.getVariable();
      if (variable != null) {
        check(variable.getOriginType(), variable.getLineNumber());
      }
      super.visitForLoop(statement);
    }
  }
}
